import { FiDownload } from "react-icons/fi";
import { Page, Section } from "../components/Page";
import { Pager } from "../components/Pager";
import { profile } from "../data/profile";
import { cvMeta, cvSections, researchInterests, type CvBlock, type CvEntry } from "../data/cv";
import { adjacent } from "../nav";

const toc = [
  { id: "interests", label: "Research interests" },
  ...cvSections.map((s) => ({ id: s.id, label: s.title })),
];

function Blocks({ blocks }: { blocks: CvBlock[] }) {
  return (
    <>
      {blocks.map((block, i) => {
        if (block.kind === "bullets") {
          return (
            <ul className="entry__points" key={i}>
              {block.items.map((item, j) => (
                <li key={j}>{item}</li>
              ))}
            </ul>
          );
        }
        if (block.kind === "labelled") {
          return (
            <p className="cv-note" key={i}>
              <strong>{block.label}{block.text ? ": " : ""}</strong>
              {block.text}
            </p>
          );
        }
        return (
          <p className="cv-note" key={i}>
            {block.text}
          </p>
        );
      })}
    </>
  );
}

function Entry({ entry, heading }: { entry: CvEntry; heading: boolean }) {
  return (
    <li>
      {heading && (
        <div className="entry__head">
          <div>
            <h3 className="entry__role">
              {entry.url ? (
                <a href={entry.url} target="_blank" rel="noopener noreferrer">
                  {entry.title}
                </a>
              ) : (
                entry.title
              )}
            </h3>
            {entry.subtitle && <div className="entry__org">{entry.subtitle}</div>}
            {entry.detail && <div className="entry__org">{entry.detail}</div>}
          </div>
          {entry.meta && <div className="entry__period">{entry.meta}</div>}
        </div>
      )}
      {entry.question && (
        <p className="cv-note">
          <strong>Research question: </strong>
          {entry.question}
        </p>
      )}
      {entry.blocks && <Blocks blocks={entry.blocks} />}
    </li>
  );
}

/**
 * The CV as real text rather than an embedded PDF viewer, so it is searchable,
 * selectable, translatable and readable by a screen reader. The PDF is the same
 * data, generated by `scripts/make-cv-pdf.mjs`, and it is tagged for the same
 * reason this page is marked up properly.
 */
export function Cv() {
  const { prev, next } = adjacent("/cv");
  const crumbs = [
    { name: "Overview", path: "/" },
    { name: "CV", path: "/cv" },
  ];

  return (
    <Page
      eyebrow="Record"
      title="Curriculum vitae"
      description="Education, publications, research, professional experience, ventures and technical skills. The same content as the PDF, as real text."
      path="/cv"
      toc={toc}
      crumbs={crumbs}
      aside={
        <div className="button-row" style={{ marginTop: "var(--space-lg)" }}>
          <a className="button button--primary" href={cvMeta.pdfPath} download>
            <FiDownload aria-hidden size={15} /> Download tagged PDF
          </a>
          <a className="button button--secondary" href={`mailto:${profile.email}`}>
            {profile.email}
          </a>
        </div>
      }
    >
      <Section id="interests" title="Research interests">
        <div className="prose">
          <p>{researchInterests}</p>
        </div>
      </Section>

      {cvSections.map((section) => {
        /* A section that is one list does not repeat its own title inside it. */
        const bare =
          section.entries.length === 1 && section.entries[0].title === section.title;
        return (
          <Section id={section.id} title={section.title} key={section.id}>
            {section.intro && (
              <div className="prose">
                <p>{section.intro}</p>
              </div>
            )}
            <ul className="entry-list">
              {section.entries.map((entry) => (
                <Entry key={entry.title} entry={entry} heading={!bare} />
              ))}
            </ul>
          </Section>
        );
      })}

      <Pager
        prev={prev && { label: prev.label, path: prev.path }}
        next={next && { label: next.label, path: next.path }}
      />
    </Page>
  );
}
